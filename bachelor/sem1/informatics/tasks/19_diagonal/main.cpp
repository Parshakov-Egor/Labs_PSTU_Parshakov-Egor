#include <iostream>
using namespace std;

int main()
{
    const int N = 5;   // размер квадратной матрицы: N строк и N столбцов
    int A[N][N];       // сама матрица, будем заполнять её по правилу

    // Напоминание о том, что такое диагонали:
    //   главная диагональ  — клетки, где i == j;
    //   побочная диагональ — клетки, где i + j == N - 1.
    //
    // Правило заполнения:
    //   если клетка лежит ОДНОВРЕМЕННО выше главной диагонали (i < j)
    //   и левее побочной диагонали (i + j < N - 1),
    //   то ставим 0, иначе ставим 1.

    cout << "=== Заполняем матрицу " << N << " x " << N << " по правилу ===" << endl;
    cout << "0 ставим в область выше главной и левее побочной диагонали," << endl;
    cout << "во всех остальных клетках будет 1." << endl;
    cout << endl;

    //  Заполнение и печать матрицы 
    for (int i = 0; i < N; i++)          // проходим по строкам
    {
        for (int j = 0; j < N; j++)      // проходим по столбцам строки i
        {
            if (i < j && i + j < N - 1)  // клетка в верхнем треугольнике между диагоналями
            {
                A[i][j] = 0;             // это «внутренняя» часть — ставим 0
            }
            else
            {
                A[i][j] = 1;             // всё остальное (диагонали и края) — ставим 1
            }

            cout << A[i][j] << " ";      // печатаем текущую клетку с пробелом
        }
        cout << endl;                    // в конце строки — переход на новую
    }

    //  Пояснение к результату 
    cout << endl;
    cout << " Готово. Матрица заполнена. " << endl;
    cout << "Область из нулей — это треугольник сверху," << endl;
    cout << "ограниченный главной и побочной диагоналями." << endl;

    return 0;
}
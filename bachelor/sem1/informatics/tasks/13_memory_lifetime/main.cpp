// Дополнительное задание 13.
// Демонстрация времени жизни динамической памяти.
// Показано, что при завершении процесса операционная система забирает память,
// но автоматический delete и вызов деструкторов при этом не выполняются.

#include <iostream>
#include <clocale>

using namespace std;

// Специальный класс с заметным деструктором.
// Если объект будет удалён через delete, на экране появится сообщение.
struct Noisy
{
    ~Noisy()
    {
        cout << "Деструктор Noisy вызван: объект корректно удалён." << endl;
    }
};

int main()
{
    setlocale(LC_ALL, "Russian");

    cout << "Демонстрация освобождения динамической памяти." << endl;
    cout << "Сначала рассмотрим правильное удаление объекта." << endl;

    Noisy* firstObject = new Noisy;
    cout << "Первый объект создан операцией new." << endl;
    delete firstObject; // Явный delete вызывает деструктор немедленно.
    firstObject = nullptr;
    cout << "Указатель первого объекта обнулён.\n" << endl;

    // Размер специально уменьшен по сравнению с исходной демонстрацией,
    // чтобы пример не занимал десятки мегабайт памяти без необходимости.
    const int ELEMENTS = 100000;
    int* data = new int[ELEMENTS];

    cout << "Создан динамический массив из " << ELEMENTS << " целых чисел." << endl;

    // Записываем только часть элементов: для демонстрации утечки не нужно
    // заполнять весь массив. Выделенный блок всё равно существует целиком.
    for (int i = 0; i < ELEMENTS; i += 1000)
        data[i] = i;

    cout << "Память массива использована, но delete[] для него не вызывается." << endl;

    Noisy* forgottenObject = new Noisy;
    cout << "Второй объект Noisy также создан, но намеренно не удаляется." << endl;

    // Это намеренная утечка в учебном примере, а не рекомендуемый стиль.
    // В реальной программе следовало бы написать:
    // delete[] data;
    // delete forgottenObject;
    (void)data;             // Подавляем предупреждение о неиспользуемом указателе.
    (void)forgottenObject;

    cout << "\nПрограмма подходит к концу." << endl;
    cout << "Операционная система освободит всю память процесса после выхода." << endl;
    cout << "Однако второго сообщения деструктора не будет: delete не выполнен." << endl;
    cout << "Вывод: завершение процесса не заменяет правильное управление памятью." << endl;

    return 0;
}

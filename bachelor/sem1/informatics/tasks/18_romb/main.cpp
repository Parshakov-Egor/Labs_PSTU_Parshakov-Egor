#include <iostream>
using namespace std;

const int N = 7;   // размер сетки: N строк и N столбцов

int main()
{
    int a[N][N];   // матрица для рисунка:
    //  1  — точка на контуре ромба
    //  0  — клетка внутри ромба
    // -1  — клетка снаружи (её мы не печатаем)

    int c1 = (N - 1) / 2;   // левый из двух центральных столбцов
    int c2 = N / 2;         // правый из двух центральных столбцов
    // (для нечётного N значения совпадают)

    cout << "=== Рисуем ромб в сетке " << N << " x " << N << " ===" << endl;
    cout << endl;

    //  Заполнение матрицы 
    for (int i = 0; i < N; i++)
    {
        // Считаем расстояние от текущей строки до верхнего или нижнего края.
        // Чем ближе к краю — тем меньше это число, значит ромб там уже.
        int w;
        if (i < N - 1 - i)
            w = i;              // строка ближе к верху
        else
            w = N - 1 - i;      // строка ближе к низу

        int left = c1 - w;     // левая граница контура в этой строке
        int right = c2 + w;     // правая граница контура в этой строке

        for (int j = 0; j < N; j++)
        {
            if (j == left || j == right)
                a[i][j] = 1;        // попали на контур ромба
            else if (j > left && j < right)
                a[i][j] = 0;        // попали внутрь ромба
            else
                a[i][j] = -1;       // попали снаружи
        }
    }

    //  Вывод результата на экран 
    cout << "Готовая картинка:" << endl;
    cout << "(1 — контур, 0 — внутренность, пустое место — снаружи)" << endl;
    cout << endl;

    for (int i = 0; i < N; i++)
    {
        for (int j = 0; j < N; j++)
        {
            if (a[i][j] == -1)
                cout << "  ";           // снаружи ничего не рисуем
            else
                cout << a[i][j] << " "; // печатаем 1 или 0 с пробелом
        }
        cout << endl;                   // переходим на новую строку
    }

    cout << endl;
    cout << "=== Готово. Ромб построен. ===" << endl;

    return 0;
}
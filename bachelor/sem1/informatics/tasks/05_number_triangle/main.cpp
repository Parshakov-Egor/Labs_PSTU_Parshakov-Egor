// Дополнительное задание 5.
// Вывести прямоугольный треугольник из символов '*'.
// Высоту треугольника задаёт пользователь.

#include <iostream>
#include <clocale>

using namespace std;

int main()
{
    setlocale(LC_ALL, "Russian");

    int height;
    cout << "Построение треугольника из звёздочек." << endl;
    cout << "Введите высоту (от 1 до 30): ";
    cin >> height;

    if (!cin || height < 1 || height > 30)
    {
        cout << "Ошибка: высота должна быть целым числом от 1 до 30." << endl;
        return 1;
    }

    cout << "\nВ каждой следующей строке будет на одну звёздочку больше." << endl;
    cout << "Слева добавляются пробелы, поэтому треугольник выравнивается вправо.\n" << endl;

    // Внешний цикл отвечает за номер строки.
    // Здесь используется префиксный ++i; для отдельного оператора в цикле
    // результат такой же, как у i++, но так запись явно показывает инкремент.
    for (int i = 1; i <= height; ++i)
    {
        // Пробелов всегда height - i: они занимают место перед звёздочками.
        for (int j = 1; j <= height - i; ++j)
            cout << " ";

        // В строке с номером i выводится ровно i звёздочек.
        for (int j = 1; j <= i; ++j)
            cout << "*";

        // Пояснение справа не участвует в рисунке, а показывает его параметры.
        cout << "  <- строка " << i << ": пробелов " << height - i
             << ", звёздочек " << i << endl;
    }

    // Сумма первых height натуральных чисел даёт общее количество звёздочек.
    int starsCount = height * (height + 1) / 2;
    cout << "\nТреугольник построен." << endl;
    cout << "Строк: " << height << ", всего звёздочек: " << starsCount << "." << endl;

    return 0;
}

// Дополнительное задание 10.
// Ханойская башня: перенести пять колец с первого стержня на третий.
// Больший диск нельзя класть на меньший, за один ход переносится один диск.

#include <iostream>
#include <clocale>

using namespace std;

// Счётчик является глобальным, чтобы рекурсивные вызовы использовали
// одно общее количество уже выполненных перемещений.
int moveCount = 0;

// Функция выполняет один ход и выводит его в понятном виде.
void moveDisk(int disk, int from, int to)
{
    ++moveCount;
    cout << "Ход " << moveCount << ": диск " << disk
         << " переносится со стержня " << from
         << " на стержень " << to << "." << endl;
}

// Рекурсивный алгоритм.
// count — сколько верхних дисков нужно перенести;
// from — исходный стержень, to — конечный, auxiliary — вспомогательный.
void solveHanoi(int count, int from, int to, int auxiliary)
{
    // База рекурсии: один диск можно сразу перенести на конечный стержень.
    if (count == 1)
    {
        moveDisk(1, from, to);
        return;
    }

    // Комментарий к трём шагам на примере count = 5:
    // 1) перенести 4 верхних диска на вспомогательный стержень;
    // 2) перенести самый большой пятый диск на конечный стержень;
    // 3) вернуть 4 диска поверх пятого.

    // Номер перемещаемого нижнего диска равен count: в каждой ветке
    // поднимается группа меньших дисков, а текущий остаётся внизу.
    solveHanoi(count - 1, from, auxiliary, to);
    moveDisk(count, from, to);
    solveHanoi(count - 1, auxiliary, to, from);
}

int main()
{
    setlocale(LC_ALL, "Russian");

    const int DISKS = 5;

    cout << "Решение задачи «Ханойская башня»." << endl;
    cout << "Количество дисков: " << DISKS << "." << endl;
    cout << "Начальный стержень: 1, конечный: 3, вспомогательный: 2." << endl;
    cout << "Ниже перечислены все перемещения в правильном порядке.\n" << endl;

    solveHanoi(DISKS, 1, 3, 2);

    // Для n дисков минимальное число ходов равно 2^n - 1.
    int expectedMoves = (1 << DISKS) - 1;

    cout << "\nПеренос башни завершён." << endl;
    cout << "Выполнено ходов: " << moveCount << "." << endl;
    cout << "Теоретический минимум: " << expectedMoves << "." << endl;

    if (moveCount == expectedMoves)
        cout << "Проверка пройдена: получен минимальный алгоритм." << endl;
    else
        cout << "Ошибка: количество ходов не совпадает с минимальным." << endl;

    return 0;
}
